// B2.1: unit tests for the SQLite -> PostgreSQL migration translator.
// Pure string tests; no database needed.
// Run: node --test test/pg-translate.test.mjs
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  translateSql, createState, splitStatements, stripComments, strftimeToPg, mapType, translateAll, UnsupportedSqlError,
} from '../scripts/pg/translate-migrations.mjs';

const backendDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tr = (sql, state) => translateSql(sql, state);
const squash = (s) => s.replace(/\s+/g, ' ');

test('INTEGER PRIMARY KEY AUTOINCREMENT becomes an identity column', () => {
  const { sql } = tr(`CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, n INTEGER NOT NULL DEFAULT 0, r REAL);`);
  assert.match(sql, /id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
  assert.match(sql, /n bigint NOT NULL DEFAULT 0/);
  assert.match(sql, /r double precision/);
  assert.doesNotMatch(sql, /AUTOINCREMENT/);
});

test('timestamps: DATETIME -> timestamptz now(); TEXT keeps the SQLite string formats', () => {
  const { sql } = tr(`CREATE TABLE IF NOT EXISTS t (
    a DATETIME DEFAULT CURRENT_TIMESTAMP,
    b TIMESTAMP NULL,
    c TEXT DEFAULT (datetime('now')),
    d TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    e TEXT DEFAULT CURRENT_TIMESTAMP
  );`);
  assert.match(sql, /^CREATE TABLE IF NOT EXISTS t \(/);
  assert.match(sql, /a timestamptz DEFAULT now\(\)/);
  assert.match(sql, /b timestamptz NULL/);
  assert.match(sql, /c text DEFAULT \(to_char\(\(now\(\) AT TIME ZONE 'UTC'\), 'YYYY-MM-DD HH24:MI:SS'\)\)/);
  assert.match(sql, /d text NOT NULL DEFAULT \(to_char\(\(now\(\) AT TIME ZONE 'UTC'\), 'YYYY-MM-DD"T"HH24:MI:SS\.MS"Z"'\)\)/);
  assert.match(sql, /e text DEFAULT \(to_char\(\(now\(\) AT TIME ZONE 'UTC'\), 'YYYY-MM-DD HH24:MI:SS'\)\)/);
  assert.equal(strftimeToPg('%Y-%m-%d %H:%M:%S'), 'YYYY-MM-DD HH24:MI:SS');
  assert.throws(() => strftimeToPg('%s'), UnsupportedSqlError);
});

test('BOOLEAN stays a 0/1 integer; JSON and JSON-looking TEXT are listed as jsonb candidates', () => {
  const { sql, notes, jsonCandidates } = tr(`CREATE TABLE t (
    f BOOLEAN DEFAULT FALSE,
    g BOOLEAN DEFAULT TRUE,
    meta JSON DEFAULT '{}',
    tags TEXT, -- JSON array
    plain TEXT DEFAULT '[]',
    name TEXT
  );`);
  assert.match(sql, /f integer DEFAULT 0/);
  assert.match(sql, /g integer DEFAULT 1/);
  assert.match(sql, /meta text DEFAULT '\{\}'/);
  assert.ok(notes.some((n) => n.includes('t.f: BOOLEAN kept as integer')));
  assert.deepEqual(jsonCandidates.sort(), ['t.meta', 't.plain', 't.tags']);
});

test('random hex ids use gen_random_uuid (no extension)', () => {
  const { sql } = tr(`CREATE TABLE t (
    id TEXT PRIMARY KEY DEFAULT (lower(hex(randomblob(16)))),
    s TEXT DEFAULT ('src_' || lower(hex(randomblob(8))))
  );`);
  assert.match(sql, /id text PRIMARY KEY DEFAULT \(replace\(gen_random_uuid\(\)::text, '-', ''\)\)/);
  assert.match(sql, /s text DEFAULT \('src_' \|\| substr\(replace\(gen_random_uuid\(\)::text, '-', ''\), 1, 16\)\)/);
  assert.throws(() => tr(`CREATE TABLE t (id TEXT DEFAULT (lower(hex(randomblob(32)))));`), UnsupportedSqlError);
});

test('CHECK, UNIQUE, table PRIMARY KEY and FOREIGN KEY constraints are kept', () => {
  const st = createState();
  tr(`CREATE TABLE parent (id TEXT PRIMARY KEY);`, st);
  const { sql, notes } = tr(`CREATE TABLE child (
    pid TEXT NOT NULL,
    v INTEGER NOT NULL CHECK (v >= 1),
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'done')),
    note TEXT CHECK (note IS NULL OR length(note) <= 500),
    run TEXT REFERENCES parent(id) ON DELETE CASCADE,
    PRIMARY KEY (pid, v),
    UNIQUE (pid, status),
    FOREIGN KEY (pid) REFERENCES parent(id) ON DELETE SET NULL
  );`, st);
  assert.deepEqual(notes, []);
  const s = squash(sql);
  assert.match(s, /v bigint NOT NULL CHECK \(v >= 1\)/);
  assert.match(s, /status text NOT NULL DEFAULT 'pending' CHECK \(status IN \('pending', 'done'\)\)/);
  assert.match(s, /note text CHECK \(note IS NULL OR length\(note\) <= 500\)/);
  assert.match(s, /run text REFERENCES parent \(id\) ON DELETE CASCADE/);
  assert.match(s, /PRIMARY KEY \(pid, v\)/);
  assert.match(s, /UNIQUE \(pid, status\)/);
  assert.match(s, /FOREIGN KEY \(pid\) REFERENCES parent \(id\) ON DELETE SET NULL/);
});

test('foreign keys PostgreSQL would refuse are dropped with a note', () => {
  const st = createState();
  tr(`CREATE TABLE users (id TEXT PRIMARY KEY);`, st);
  const { sql, notes } = tr(`CREATE TABLE x (
    a TEXT, b INTEGER,
    FOREIGN KEY (a) REFERENCES missing(id),
    FOREIGN KEY (b) REFERENCES users(id) ON DELETE CASCADE
  );`, st);
  assert.doesNotMatch(sql, /REFERENCES/);
  assert.ok(notes.some((n) => /REFERENCES missing dropped \(table missing does not exist\)/.test(n)));
  assert.ok(notes.some((n) => /REFERENCES users dropped \(type mismatch bigint -> text\)/.test(n)));
});

test('indexes: partial WHERE kept, COLLATE NOCASE dropped with a note', () => {
  const st = createState();
  tr(`CREATE TABLE t (a TEXT, b INTEGER, c TEXT);`, st);
  const { sql, notes } = tr(`
    CREATE UNIQUE INDEX IF NOT EXISTS ix_one ON t(a) WHERE c IN ('x', 'y');
    CREATE INDEX IF NOT EXISTS ix_b ON t(b DESC, a) WHERE b = 1;
    CREATE INDEX ix_ci ON t(c COLLATE NOCASE);`, st);
  assert.match(sql, /CREATE UNIQUE INDEX IF NOT EXISTS ix_one ON t \(a\) WHERE c IN \('x', 'y'\);/);
  assert.match(sql, /CREATE INDEX IF NOT EXISTS ix_b ON t \(b DESC, a\) WHERE b = 1;/);
  assert.match(sql, /CREATE INDEX ix_ci ON t \(c\);/);
  assert.ok(notes.some((n) => n.includes('COLLATE NOCASE dropped')));
  const col = tr(`CREATE TABLE u (name TEXT NOT NULL COLLATE NOCASE UNIQUE);`);
  assert.match(col.sql, /name text NOT NULL UNIQUE/);
  assert.ok(col.notes.some((n) => n.includes('u.name: COLLATE NOCASE dropped')));
});

test('INSERT OR IGNORE -> ON CONFLICT DO NOTHING; INSERT OR REPLACE needs an override', () => {
  const { sql } = tr(`INSERT OR IGNORE INTO t (a, b) SELECT id, datetime('now') FROM s WHERE x = 1;`);
  assert.equal(squash(sql).trim(), `INSERT INTO t (a, b) SELECT id, to_char((now() AT TIME ZONE 'UTC'), 'YYYY-MM-DD HH24:MI:SS') FROM s WHERE x = 1 ON CONFLICT DO NOTHING;`);
  assert.throws(() => tr(`INSERT OR REPLACE INTO t (a) VALUES (1);`), UnsupportedSqlError);
  assert.throws(() => tr(`UPDATE t SET a = json_extract(b, '$.x');`), UnsupportedSqlError);
  assert.throws(() => tr(`SELECT * FROM t WHERE a GLOB 'x*';`), UnsupportedSqlError);
});

test('ALTER TABLE ADD COLUMN / RENAME and PRAGMA', () => {
  const st = createState();
  tr(`CREATE TABLE t (id TEXT PRIMARY KEY);`, st);
  const { sql, notes } = tr(`
    PRAGMA foreign_keys = OFF;
    ALTER TABLE t ADD COLUMN state TEXT NOT NULL DEFAULT 'idle' CHECK(state IN ('idle', 'run'));
    ALTER TABLE t ADD COLUMN locked_until TIMESTAMP NULL;
    ALTER TABLE t RENAME TO t2;`, st);
  assert.match(sql, /ALTER TABLE t ADD COLUMN state text NOT NULL DEFAULT 'idle' CHECK \(state IN \('idle', 'run'\)\);/);
  assert.match(sql, /ALTER TABLE t ADD COLUMN locked_until timestamptz NULL;/);
  assert.match(sql, /ALTER TABLE t RENAME TO t2;/);
  assert.doesNotMatch(sql, /PRAGMA/);
  assert.ok(notes.some((n) => n.startsWith('dropped: PRAGMA')));
  assert.ok(st.tables.has('t2') && !st.tables.has('t'));
  assert.ok(st.tables.get('t2').cols.has('state'));
});

test('version trigger becomes a plpgsql BEFORE UPDATE trigger; DROP TRIGGER finds its table', () => {
  const st = createState();
  tr(`CREATE TABLE agents_config (id TEXT PRIMARY KEY, name TEXT, version INTEGER NOT NULL DEFAULT 1);`, st);
  const src = `CREATE TRIGGER IF NOT EXISTS trg_v
AFTER UPDATE OF name ON agents_config
WHEN NEW.version = OLD.version
BEGIN
  UPDATE agents_config SET version = OLD.version + 1 WHERE id = NEW.id;
END;`;
  assert.equal(splitStatements(stripComments(src)).length, 1);
  const { sql } = tr(src, st);
  assert.match(sql, /CREATE OR REPLACE FUNCTION trg_v_fn\(\) RETURNS trigger LANGUAGE plpgsql/);
  assert.match(sql, /NEW\.version := OLD\.version \+ 1;\s+RETURN NEW;/);
  assert.match(sql, /BEFORE UPDATE OF name ON agents_config\s+FOR EACH ROW\s+WHEN \(NEW\.version = OLD\.version\)\s+EXECUTE FUNCTION trg_v_fn\(\)/);
  assert.match(sql, /IF NOT EXISTS \(SELECT 1 FROM pg_trigger WHERE tgname = 'trg_v'/);
  assert.equal(tr(`DROP TRIGGER IF EXISTS trg_v;`, st).sql.trim(), 'DROP TRIGGER IF EXISTS trg_v ON agents_config;');
  assert.match(tr(`DROP TRIGGER IF EXISTS never_made;`, st).sql, /nothing to drop/);

  // any other body: AFTER trigger running the statements as written
  tr(`CREATE TABLE log (id INTEGER PRIMARY KEY AUTOINCREMENT, agent TEXT);`, st);
  const other = tr(`CREATE TRIGGER trg_log AFTER INSERT ON agents_config BEGIN INSERT INTO log (agent) VALUES (NEW.id); END;`, st).sql;
  assert.match(other, /INSERT INTO log \(agent\) VALUES \(NEW\.id\);\s+RETURN NULL;/);
  assert.match(other, /CREATE TRIGGER trg_log\s+AFTER INSERT ON agents_config/);
});

test('comments and quotes: -- inside strings survives, comments go', () => {
  const { sql } = tr(`-- header\nINSERT INTO t (a) VALUES ('a -- b; c'); /* x */ UPDATE t SET a = 'd' WHERE a = 'e'; -- tail`);
  assert.match(sql, /VALUES \('a -- b; c'\);/);
  assert.match(sql, /UPDATE t SET a = 'd' WHERE a = 'e';/);
  assert.doesNotMatch(sql, /header|tail/);
});

test('type mapping', () => {
  assert.deepEqual(mapType('INTEGER'), { pg: 'bigint', kind: 'int' });
  assert.deepEqual(mapType('BOOLEAN'), { pg: 'integer', kind: 'bool' });
  assert.deepEqual(mapType('DATETIME'), { pg: 'timestamptz', kind: 'ts' });
  assert.deepEqual(mapType('BLOB'), { pg: 'bytea', kind: 'blob' });
  assert.deepEqual(mapType('VARCHAR'), { pg: 'text', kind: 'text' });
  assert.deepEqual(mapType(''), { pg: 'text', kind: 'text' });
});

test('the committed migrations-pg files match the translator output for every migration', () => {
  const results = translateAll(backendDir);
  const sources = readdirSyncSorted(join(backendDir, 'src', 'db', 'migrations'));
  assert.equal(results.length, sources.length + 1, 'one output per migration plus 000_schema');
  for (const r of results) {
    const p = join(backendDir, 'src', 'db', 'migrations-pg', r.file);
    assert.ok(existsSync(p), `${r.file} missing; run node scripts/pg/translate-migrations.mjs`);
    assert.equal(readFileSync(p, 'utf8'), r.content, `${r.file} out of date; run node scripts/pg/translate-migrations.mjs`);
  }
});

function readdirSyncSorted(dir) {
  return readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
}
