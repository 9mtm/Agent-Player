/**
 * Map a declared SQLite column type to PostgreSQL.
 * kind: int | bool | real | text | ts | date | blob | numeric | json
 */
export function mapType(decl) {
  const t = (decl || '').trim().toUpperCase().replace(/\s+/g, ' ');
  if (t === '') return { pg: 'text', kind: 'text' };
  if (t === 'BOOLEAN' || t === 'BOOL') return { pg: 'integer', kind: 'bool' };
  if (t === 'DATETIME' || t.startsWith('TIMESTAMP')) return { pg: 'timestamptz', kind: 'ts' };
  if (t === 'DATE') return { pg: 'date', kind: 'date' };
  if (t === 'JSON') return { pg: 'text', kind: 'json' };
  if (t.includes('INT')) return { pg: 'bigint', kind: 'int' };
  if (t.includes('CHAR') || t.includes('CLOB') || t.includes('TEXT')) return { pg: 'text', kind: 'text' };
  if (t.includes('BLOB')) return { pg: 'bytea', kind: 'blob' };
  if (t.includes('REAL') || t.includes('FLOA') || t.includes('DOUB')) return { pg: 'double precision', kind: 'real' };
  if (t.startsWith('NUMERIC') || t.startsWith('DECIMAL')) return { pg: t.toLowerCase(), kind: 'numeric' };
  throw new UnsupportedSqlError(`unknown column type: ${decl}`);
}

/** SQLite strftime format -> PostgreSQL to_char format. */
export function strftimeToPg(fmt) {
  const map = { Y: 'YYYY', m: 'MM', d: 'DD', H: 'HH24', M: 'MI', S: 'SS', f: 'SS.MS', j: 'DDD', s: null, w: 'D', W: 'WW' };
  let out = '';
  let lit = '';
  const flush = () => { if (lit) { out += `"${lit}"`; lit = ''; } };
  for (let i = 0; i < fmt.length; i++) {
    if (fmt[i] === '%') {
      const k = fmt[++i];
      if (k === '%') { lit += '%'; continue; }
      if (!map[k]) throw new UnsupportedSqlError(`strftime format %${k} not supported`);
      flush();
      out += map[k];
    } else if (/[A-Za-z]/.test(fmt[i])) {
      lit += fmt[i];
    } else {
      flush();
      out += fmt[i];
    }
  }
  flush();
  return out;
}

function hexRandom(n) {
  const bytes = Number(n);
  if (!(bytes >= 1 && bytes <= 16)) throw new UnsupportedSqlError(`randomblob(${n}) longer than 16 bytes`);
  const full = `replace(gen_random_uuid()::text, '-', '')`;
  return bytes === 16 ? full : `substr(${full}, 1, ${bytes * 2})`;
}

/**
 * Rewrite SQLite-only functions in an expression or DML statement.
 * `kind` is the target column kind when the expression is a column default.
 */
export function translateExpr(expr, kind = 'text') {
  let s = expr;
  s = s.replace(/lower\s*\(\s*hex\s*\(\s*randomblob\s*\(\s*(\d+)\s*\)\s*\)\s*\)/gi, (_, n) => hexRandom(n));
  s = s.replace(/strftime\s*\(\s*'([^']*)'\s*,\s*'now'\s*\)/gi, (_, f) => (kind === 'ts' ? 'now()' : `to_char((now() AT TIME ZONE 'UTC'), '${strftimeToPg(f)}')`));
  s = s.replace(/datetime\s*\(\s*'now'\s*\)/gi, () => (kind === 'ts' ? 'now()' : TEXT_NOW));
  s = s.replace(/date\s*\(\s*'now'\s*\)/gi, () => (kind === 'date' ? 'CURRENT_DATE' : `to_char((now() AT TIME ZONE 'UTC'), 'YYYY-MM-DD')`));
  s = s.replace(/\bIFNULL\s*\(/gi, 'COALESCE(');
  const bad = /\b(strftime|datetime|julianday|unixepoch|randomblob|json_\w+|json|last_insert_rowid|changes|GLOB|typeof|printf|instr)\s*\(|\bGLOB\b|\bRAISE\s*\(/i.exec(s);
  if (bad) throw new UnsupportedSqlError(`no automatic translation for ${bad[0]} in: ${expr.trim().slice(0, 120)}`);
  return s;
}

/** Translate a DEFAULT value for a column of the given kind. */
export function translateDefault(value, kind) {
  const v = value.trim();
  const U = v.toUpperCase();
  if (U === 'CURRENT_TIMESTAMP') return kind === 'ts' ? 'now()' : kind === 'date' ? 'CURRENT_DATE' : `(${TEXT_NOW})`;
  if (U === 'CURRENT_DATE') return kind === 'date' ? 'CURRENT_DATE' : `(to_char((now() AT TIME ZONE 'UTC'), 'YYYY-MM-DD'))`;
  if (U === 'TRUE' || U === 'FALSE') {
    if (kind === 'bool' || kind === 'int' || kind === 'real') return U === 'TRUE' ? '1' : '0';
    return U;
  }
  if (v.startsWith('(')) return `(${translateExpr(v.slice(1, -1), kind).trim()})`;
  return translateExpr(v, kind);
}

function isJsonCandidate(name, kind, defaultValue, hinted) {
  if (kind === 'json') return true;
  if (kind !== 'text') return false;
  if (hinted) return true;
  if (defaultValue && /^'\s*[[{]/.test(defaultValue)) return true;
  return JSON_NAME_RE.test(name) && !/(_id|_url|_name)$/.test(name);
}

