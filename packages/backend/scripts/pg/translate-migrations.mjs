/** Remove -- and /* *\/ comments outside string literals and quoted identifiers. */
export function stripComments(sql) {
  let out = '';
  for (let i = 0; i < sql.length; i++) {
    const c = sql[i];
    if (c === "'" || c === '"' || c === '`') {
      const j = endOfQuoted(sql, i);
      out += sql.slice(i, j);
      i = j - 1;
    } else if (c === '-' && sql[i + 1] === '-') {
      while (i < sql.length && sql[i] !== '\n') i++;
      out += '\n';
    } else if (c === '/' && sql[i + 1] === '*') {
      const j = sql.indexOf('*/', i + 2);
      i = j < 0 ? sql.length : j + 1;
      out += ' ';
    } else {
      out += c;
    }
  }
  return out;
}

function endOfQuoted(s, i) {
  const q = s[i];
  let j = i + 1;
  while (j < s.length) {
    if (s[j] === q) {
      if (s[j + 1] === q) { j += 2; continue; }
      return j + 1;
    }
    j++;
  }
  throw new UnsupportedSqlError(`unterminated quote at ${i}`);
}

/** Index just after the parenthesis that closes the one at `i`. */
function endOfParen(s, i) {
  let depth = 0;
  for (let j = i; j < s.length; j++) {
    const c = s[j];
    if (c === "'" || c === '"' || c === '`') { j = endOfQuoted(s, j) - 1; continue; }
    if (c === '(') depth++;
    else if (c === ')') { depth--; if (depth === 0) return j + 1; }
  }
  throw new UnsupportedSqlError('unbalanced parentheses');
}

/** Split a script into statements (a trigger body keeps its inner semicolons). */
export function splitStatements(sql) {
  const out = [];
  let start = 0;
  for (let i = 0; i < sql.length; i++) {
    const c = sql[i];
    if (c === "'" || c === '"' || c === '`') { i = endOfQuoted(sql, i) - 1; continue; }
    if (c !== ';') continue;
    const cur = sql.slice(start, i);
    if (/^\s*CREATE\s+(TEMP\w*\s+)?TRIGGER\b/i.test(cur) && !/\bEND\s*$/i.test(cur)) continue;
    if (cur.trim()) out.push(cur.trim());
    start = i + 1;
  }
  const tail = sql.slice(start).trim();
  if (tail) out.push(tail);
  return out;
}

/** Split on top-level commas. */
export function splitTopLevel(s) {
  const parts = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (c === "'" || c === '"' || c === '`') { i = endOfQuoted(s, i) - 1; continue; }
    if (c === '(') depth++;
    else if (c === ')') depth--;
    else if (c === ',' && depth === 0) { parts.push(s.slice(start, i).trim()); start = i + 1; }
  }
  const last = s.slice(start).trim();
  if (last) parts.push(last);
  return parts;
}

/** Tokens: words/numbers, 'strings', "identifiers", (balanced groups), single chars. */
export function tokenize(s) {
  const toks = [];
  let i = 0;
  while (i < s.length) {
    const c = s[i];
    if (/\s/.test(c)) { i++; continue; }
    if (c === "'" || c === '"' || c === '`') { const j = endOfQuoted(s, i); toks.push(s.slice(i, j)); i = j; continue; }
    if (c === '[') { const j = s.indexOf(']', i); toks.push('"' + s.slice(i + 1, j) + '"'); i = j + 1; continue; }
    if (c === '(') { const j = endOfParen(s, i); toks.push(s.slice(i, j)); i = j; continue; }
    const m = /^[A-Za-z0-9_.$]+/.exec(s.slice(i));
    if (m) { toks.push(m[0]); i += m[0].length; continue; }
    const op = /^(\|\||<=|>=|<>|!=|==)/.exec(s.slice(i));
    if (op) { toks.push(op[0]); i += op[0].length; continue; }
    toks.push(c); i++;
  }
  return toks;
}

const unquote = (id) => (/^["`]/.test(id) ? id.slice(1, -1).replace(/""/g, '"') : id);
const quoteIdent = (id) => (PG_RESERVED.has(id.toLowerCase()) || !/^[a-z_][a-z0-9_$]*$/.test(id) ? `"${id.replace(/"/g, '""')}"` : id);
const upper = (t) => (t || '').toUpperCase();

