export function createState() {
  return { tables: new Map(), triggers: new Map() };
}

function tableInfo(state, name) {
  return state.tables.get(name.toLowerCase());
}

/** Translate one column definition. Returns { sql, name, pg, kind, pk }. */
function translateColumn(def, table, ctx, cols) {
  const toks = tokenize(def);
  const name = unquote(toks[0]);
  let i = 1;
  const typeWords = [];
  while (i < toks.length && /^[A-Za-z_]\w*$/.test(toks[i]) && !COLUMN_CONSTRAINT_WORDS.has(upper(toks[i]))) typeWords.push(toks[i++]);
  if (i < toks.length && toks[i].startsWith('(') && typeWords.length) typeWords.push(toks[i++]);
  const declType = typeWords.join(' ');
  const { pg, kind } = mapType(declType.replace(/\(.*\)$/, ''));
  const rest = toks.slice(i);
  const restUpper = rest.map(upper);
  const pkAt = restUpper.findIndex((t, k) => t === 'PRIMARY' && restUpper[k + 1] === 'KEY');
  const isPk = pkAt >= 0;
  const identity = isPk && kind === 'int' && /^INTEGER$/i.test(declType.trim());
  let pgType = pg;
  if (identity) pgType = 'bigint GENERATED BY DEFAULT AS IDENTITY';
  if (restUpper.includes('AUTOINCREMENT') && !identity) throw new UnsupportedSqlError(`AUTOINCREMENT on non-INTEGER column ${table}.${name}`);
  cols.push({ name, pg, kind, pk: isPk }); // known before FK checks (self reference)

  const out = [];
  let defaultValue = null;
  for (let k = 0; k < rest.length; k++) {
    const t = rest[k];
    const T = upper(t);
    if (T === 'AUTOINCREMENT') continue;
    if (T === 'COLLATE') {
      ctx.notes.push(`${table}.${name}: COLLATE ${rest[k + 1]} dropped (PostgreSQL compares case-sensitively; use lower() or citext in B2.2 if needed)`);
      k++;
      continue;
    }
    if (T === 'DEFAULT') {
      let v = rest[++k];
      if ((v === '-' || v === '+') && k + 1 < rest.length) v += rest[++k];
      defaultValue = v;
      out.push('DEFAULT', translateDefault(v, kind));
      continue;
    }
    if (T === 'CHECK') {
      out.push('CHECK', translateExpr(rest[++k]));
      continue;
    }
    if (T === 'REFERENCES') {
      const clause = ['REFERENCES', rest[++k]];
      if (rest[k + 1] && rest[k + 1].startsWith('(')) clause.push(rest[++k]);
      for (;;) {
        const N = upper(rest[k + 1]);
        if (N === 'ON') {
          clause.push(rest[++k], rest[++k]);
          const act = upper(rest[k + 1]);
          clause.push(rest[++k]);
          if (act === 'SET' || act === 'NO') clause.push(rest[++k]);
        } else if (N === 'MATCH' || N === 'INITIALLY') {
          clause.push(rest[++k], rest[++k]);
        } else if (N === 'DEFERRABLE') {
          clause.push(rest[++k]);
        } else if (N === 'NOT' && upper(rest[k + 2]) === 'DEFERRABLE') {
          clause.push(rest[++k], rest[++k]);
        } else break;
      }
      const refTable = unquote(clause[1]);
      const refCols = clause[2] && clause[2].startsWith('(') ? splitTopLevel(clause[2].slice(1, -1)).map(unquote) : null;
      const why = fkProblem(ctx.state, table, cols, [name], refTable, refCols);
      if (why) { ctx.notes.push(`${table}.${name}: REFERENCES ${refTable} dropped (${why})`); continue; }
      out.push(...clause);
      continue;
    }
    out.push(t);
  }
  const hinted = ctx.jsonHints.has(`${table}.${name}`.toLowerCase());
  if (isJsonCandidate(name, kind, defaultValue, hinted)) ctx.jsonCandidates.push(`${table}.${name}`);
  if (kind === 'bool') ctx.notes.push(`${table}.${name}: BOOLEAN kept as integer 0/1 (boolean candidate)`);
  return { sql: [quoteIdent(name), pgType, ...out].join(' ').replace(/\s+/g, ' ').trim(), name, pg, kind, pk: isPk };
}

/** Why a foreign key cannot exist in PostgreSQL, or null when it is fine. */
function fkProblem(state, table, cols, fromCols, refTable, refCols) {
  const self = refTable.toLowerCase() === table.toLowerCase();
  const ref = self ? { cols: new Map(cols.map((c) => [c.name.toLowerCase(), c])), pk: cols.filter((c) => c.pk).map((c) => c.name) } : tableInfo(state, refTable);
  if (!ref) return `table ${refTable} does not exist`;
  const targets = refCols || ref.pk;
  if (!targets || targets.length !== fromCols.length) return `no matching key on ${refTable}`;
  for (let n = 0; n < fromCols.length; n++) {
    const a = cols.find((c) => c.name.toLowerCase() === fromCols[n].toLowerCase());
    const b = ref.cols.get(targets[n].toLowerCase());
    if (!b) return `column ${refTable}.${targets[n]} does not exist`;
    if (a && b && a.pg !== b.pg) return `type mismatch ${a.pg} -> ${b.pg}`;
  }
  return null;
}

function translateCreateTable(stmt, ctx) {
  const m = /^CREATE\s+(TEMP\w*\s+)?TABLE\s+(IF\s+NOT\s+EXISTS\s+)?("[^"]+"|`[^`]+`|[\w.]+)\s*\(/i.exec(stmt);
  if (!m) throw new UnsupportedSqlError(`cannot parse CREATE TABLE: ${stmt.slice(0, 80)}`);
  if (m[1]) throw new UnsupportedSqlError('TEMP tables are not migrated');
  const table = unquote(m[3]);
  const open = m[0].length - 1;
  const close = endOfParen(stmt, open);
  const trailing = stmt.slice(close).trim();
  if (/^AS\b/i.test(trailing)) throw new UnsupportedSqlError('CREATE TABLE AS');
  if (trailing) ctx.notes.push(`${table}: table option "${trailing}" dropped`);
  const parts = splitTopLevel(stmt.slice(open + 1, close - 1));
  const cols = [];
  const colSql = [];
  const tableConstraints = [];
  for (const p of parts) {
    const first = upper(tokenize(p)[0]);
    if (['CONSTRAINT', 'PRIMARY', 'UNIQUE', 'CHECK', 'FOREIGN'].includes(first)) tableConstraints.push(p);
    else colSql.push(translateColumn(p, table, ctx, cols));
  }
  const tablePk = [];
  const consSql = [];
  for (const c of tableConstraints) {
    const toks = tokenize(c);
    const T = toks.map(upper);
    let k = 0;
    let prefix = '';
    if (T[0] === 'CONSTRAINT') { prefix = `CONSTRAINT ${quoteIdent(unquote(toks[1]))} `; k = 2; }
    if (T[k] === 'PRIMARY') {
      const list = splitTopLevel(toks[k + 2].slice(1, -1)).map(unquote);
      tablePk.push(...list);
      consSql.push(`${prefix}PRIMARY KEY (${list.map(quoteIdent).join(', ')})`);
    } else if (T[k] === 'UNIQUE') {
      const list = splitTopLevel(toks[k + 1].slice(1, -1)).map((x) => unquote(x.replace(/\s+COLLATE\s+\w+/i, '')));
      consSql.push(`${prefix}UNIQUE (${list.map(quoteIdent).join(', ')})`);
    } else if (T[k] === 'CHECK') {
      consSql.push(`${prefix}CHECK ${translateExpr(toks[k + 1])}`);
    } else if (T[k] === 'FOREIGN') {
      const from = splitTopLevel(toks[k + 2].slice(1, -1)).map(unquote);
      const refTable = unquote(toks[k + 4]);
      const hasRefCols = toks[k + 5] && toks[k + 5].startsWith('(');
      const refCols = hasRefCols ? splitTopLevel(toks[k + 5].slice(1, -1)).map(unquote) : null;
      const tail = toks.slice(k + (hasRefCols ? 6 : 5)).join(' ');
      const why = fkProblem(ctx.state, table, cols.map((c) => ({ ...c, pk: c.pk || tablePk.includes(c.name) })), from, refTable, refCols);
      if (why) { ctx.notes.push(`${table}: FOREIGN KEY (${from.join(', ')}) REFERENCES ${refTable} dropped (${why})`); continue; }
      consSql.push(`${prefix}FOREIGN KEY (${from.map(quoteIdent).join(', ')}) REFERENCES ${quoteIdent(refTable)}${refCols ? ` (${refCols.map(quoteIdent).join(', ')})` : ''}${tail ? ' ' + tail : ''}`);
    }
  }
  const pkCols = colSql.filter((c) => c.pk).map((c) => c.name);
  ctx.state.tables.set(table.toLowerCase(), {
    name: table,
    cols: new Map(cols.map((c) => [c.name.toLowerCase(), c])),
    pk: pkCols.length ? pkCols : tablePk,
  });
  const ine = m[2] ? 'IF NOT EXISTS ' : '';
  const body = [...colSql.map((c) => c.sql), ...consSql].map((l) => '  ' + l).join(',\n');
  return `CREATE TABLE ${ine}${quoteIdent(table)} (\n${body}\n);`;
}

function translateCreateIndex(stmt, ctx) {
  const m = /^CREATE\s+(UNIQUE\s+)?INDEX\s+(IF\s+NOT\s+EXISTS\s+)?([\w"]+)\s+ON\s+([\w"]+)\s*\(/i.exec(stmt);
  if (!m) throw new UnsupportedSqlError(`cannot parse CREATE INDEX: ${stmt.slice(0, 80)}`);
  const open = m[0].length - 1;
  const close = endOfParen(stmt, open);
  let cols = stmt.slice(open + 1, close - 1);
  if (/COLLATE\s+NOCASE/i.test(cols)) {
    ctx.notes.push(`index ${unquote(m[3])}: COLLATE NOCASE dropped`);
    cols = cols.replace(/\s+COLLATE\s+NOCASE/gi, '');
  }
  const rest = stmt.slice(close).trim();
  let where = '';
  if (rest) {
    const w = /^WHERE\s+([\s\S]+)$/i.exec(rest);
    if (!w) throw new UnsupportedSqlError(`index tail not understood: ${rest}`);
    where = ` WHERE ${translateExpr(w[1]).trim()}`;
  }
  const colList = splitTopLevel(cols).map((c) => c.replace(/\s+/g, ' ')).join(', ');
  return `CREATE ${m[1] ? 'UNIQUE ' : ''}INDEX ${m[2] ? 'IF NOT EXISTS ' : ''}${unquote(m[3])} ON ${quoteIdent(unquote(m[4]))} (${colList})${where};`;
}

function translateAlterTable(stmt, ctx) {
  const m = /^ALTER\s+TABLE\s+([\w"]+)\s+([\s\S]+)$/i.exec(stmt);
  if (!m) throw new UnsupportedSqlError(`cannot parse ALTER TABLE: ${stmt.slice(0, 80)}`);
  const table = unquote(m[1]);
  const action = m[2].trim();
  const info = tableInfo(ctx.state, table);
  let a;
  if ((a = /^ADD\s+(COLUMN\s+)?([\s\S]+)$/i.exec(action))) {
    if (!info) throw new UnsupportedSqlError(`ALTER TABLE on unknown table ${table}`);
    const cols = [...info.cols.values()];
    const col = translateColumn(a[2], table, ctx, cols);
    if (col.pk) throw new UnsupportedSqlError('ADD COLUMN ... PRIMARY KEY');
    info.cols.set(col.name.toLowerCase(), cols[cols.length - 1]);
    return `ALTER TABLE ${quoteIdent(table)} ADD COLUMN ${col.sql};`;
  }
  if ((a = /^RENAME\s+TO\s+([\w"]+)$/i.exec(action))) {
    const to = unquote(a[1]);
    if (info) {
      ctx.state.tables.delete(table.toLowerCase());
      info.name = to;
      ctx.state.tables.set(to.toLowerCase(), info);
    }
    for (const [trg, t] of ctx.state.triggers) if (t.toLowerCase() === table.toLowerCase()) ctx.state.triggers.set(trg, to);
    ctx.notes.push(`${table} -> ${to}: constraint names keep the old table name in PostgreSQL (e.g. ${table}_pkey)`);
    return `ALTER TABLE ${quoteIdent(table)} RENAME TO ${quoteIdent(to)};`;
  }
  if ((a = /^RENAME\s+(COLUMN\s+)?([\w"]+)\s+TO\s+([\w"]+)$/i.exec(action))) {
    const from = unquote(a[2]);
    const to = unquote(a[3]);
    if (info && info.cols.has(from.toLowerCase())) {
      const c = info.cols.get(from.toLowerCase());
      info.cols.delete(from.toLowerCase());
      c.name = to;
      info.cols.set(to.toLowerCase(), c);
    }
    return `ALTER TABLE ${quoteIdent(table)} RENAME COLUMN ${quoteIdent(from)} TO ${quoteIdent(to)};`;
  }
  if ((a = /^DROP\s+(COLUMN\s+)?([\w"]+)$/i.exec(action))) {
    const col = unquote(a[2]);
    if (info) info.cols.delete(col.toLowerCase());
    return `ALTER TABLE ${quoteIdent(table)} DROP COLUMN ${quoteIdent(col)};`;
  }
  throw new UnsupportedSqlError(`ALTER TABLE action not supported: ${action.slice(0, 80)}`);
}

function translateTrigger(stmt, ctx) {
  const m = /^CREATE\s+TRIGGER\s+(IF\s+NOT\s+EXISTS\s+)?(\w+)\s+(BEFORE|AFTER|INSTEAD\s+OF)?\s*(INSERT|DELETE|UPDATE(?:\s+OF\s+([\w\s,]+?))?)\s+ON\s+(\w+)\s+(FOR\s+EACH\s+ROW\s+)?(?:WHEN\s+([\s\S]+?)\s+)?BEGIN\s+([\s\S]*?)\s*END$/i.exec(stmt);
  if (!m) throw new UnsupportedSqlError(`cannot parse CREATE TRIGGER: ${stmt.slice(0, 80)}`);
  const [, ifne, name, timingRaw, eventRaw, ofCols, table, , when, bodyRaw] = m;
  const timing = (timingRaw || 'BEFORE').toUpperCase().replace(/\s+/g, ' ');
  if (timing === 'INSTEAD OF') throw new UnsupportedSqlError('INSTEAD OF triggers');
  const event = eventRaw.trim().split(/\s+/)[0].toUpperCase();
  const cols = ofCols ? ofCols.split(',').map((c) => c.trim()).filter(Boolean) : [];
  const bodyStmts = splitStatements(bodyRaw);
  const info = tableInfo(ctx.state, table);
  const fn = `${name}_fn`;
  let pgTiming = timing;
  let fnBody;

  // Fast path: AFTER UPDATE whose only action updates the same row by its
  // primary key -> BEFORE UPDATE that assigns NEW.<col> directly.
  const selfUpdate = bodyStmts.length === 1 && /^UPDATE\s+(\w+)\s+SET\s+([\s\S]+?)\s+WHERE\s+(\w+)\s*=\s*NEW\.(\w+)$/i.exec(bodyStmts[0]);
  if (event === 'UPDATE' && timing === 'AFTER' && selfUpdate && selfUpdate[1].toLowerCase() === table.toLowerCase()
      && info && info.pk.length === 1 && info.pk[0].toLowerCase() === selfUpdate[3].toLowerCase()
      && selfUpdate[3].toLowerCase() === selfUpdate[4].toLowerCase()) {
    const sets = splitTopLevel(selfUpdate[2]).map((a) => {
      const s = /^(\w+)\s*=\s*([\s\S]+)$/.exec(a);
      if (!s) throw new UnsupportedSqlError(`trigger SET not understood: ${a}`);
      return `  NEW.${quoteIdent(s[1])} := ${translateExpr(s[2]).trim()};`;
    });
    pgTiming = 'BEFORE';
    fnBody = `${sets.join('\n')}\n  RETURN NEW;`;
    ctx.notes.push(`trigger ${name}: AFTER UPDATE self-row UPDATE rewritten as BEFORE UPDATE (same result; UPDATE ... RETURNING now sees the bumped value)`);
  } else {
    fnBody = bodyStmts.map((s) => `  ${translateExpr(s).trim()};`).join('\n') + `\n  RETURN ${timing === 'AFTER' ? 'NULL' : event === 'DELETE' ? 'OLD' : 'NEW'};`;
  }
  ctx.state.triggers.set(name, table);
  const create = `CREATE TRIGGER ${name}\n  ${pgTiming} ${event}${cols.length ? ' OF ' + cols.map(quoteIdent).join(', ') : ''} ON ${quoteIdent(table)}\n  FOR EACH ROW${when ? `\n  WHEN (${translateExpr(when).trim()})` : ''}\n  EXECUTE FUNCTION ${fn}()`;
  const fnSql = `CREATE OR REPLACE FUNCTION ${fn}() RETURNS trigger LANGUAGE plpgsql AS $fn$\nBEGIN\n${fnBody}\nEND\n$fn$;`;
  const trg = ifne
    ? `DO $do$\nBEGIN\n  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = '${name}' AND tgrelid = '${table}'::regclass) THEN\n    ${create.replace(/\n/g, '\n    ')};\n  END IF;\nEND\n$do$;`
    : `${create};`;
  return `${fnSql}\n${trg}`;
}

function translateDrop(stmt, ctx) {
  const m = /^DROP\s+(TABLE|INDEX|VIEW|TRIGGER)\s+(IF\s+EXISTS\s+)?([\w"]+)$/i.exec(stmt);
  if (!m) throw new UnsupportedSqlError(`cannot parse DROP: ${stmt.slice(0, 80)}`);
  const kind = m[1].toUpperCase();
  const name = unquote(m[3]);
  const ie = m[2] ? 'IF EXISTS ' : '';
  if (kind === 'TABLE') {
    ctx.state.tables.delete(name.toLowerCase());
    for (const [trg, t] of ctx.state.triggers) if (t.toLowerCase() === name.toLowerCase()) ctx.state.triggers.delete(trg);
  }
  if (kind === 'TRIGGER') {
    const table = ctx.state.triggers.get(name);
    if (!table) {
      if (!ie) throw new UnsupportedSqlError(`DROP TRIGGER ${name}: table unknown`);
      return `-- DROP TRIGGER IF EXISTS ${name}: trigger never created, nothing to drop`;
    }
    ctx.state.triggers.delete(name);
    return `DROP TRIGGER ${ie}${name} ON ${quoteIdent(table)};`;
  }
  return `DROP ${kind} ${ie}${quoteIdent(name)};`;
}

function translateInsert(stmt, ctx) {
  const m = /^INSERT\s+OR\s+(\w+)\s+INTO\b/i.exec(stmt);
  if (!m) return `${translateExpr(stmt).trim()};`;
  const how = m[1].toUpperCase();
  if (how !== 'IGNORE') throw new UnsupportedSqlError(`INSERT OR ${how} needs a hand-written ON CONFLICT target`);
  return `${translateExpr(stmt.replace(/^INSERT\s+OR\s+IGNORE\s+INTO\b/i, 'INSERT INTO')).trim()}\nON CONFLICT DO NOTHING;`;
}

/** Translate one statement (comments already stripped). Returns SQL or '' (dropped). */
export function translateStatement(stmt, ctx) {
  const s = stmt.trim().replace(/;\s*$/, '');
  if (!s) return '';
  const head = s.slice(0, 40).toUpperCase().replace(/\s+/g, ' ');
  if (head.startsWith('PRAGMA')) { ctx.notes.push(`dropped: ${s.split('\n')[0]}`); return ''; }
  if (/^(BEGIN|COMMIT|END)( TRANSACTION)?$/.test(head)) { ctx.notes.push(`dropped: ${s}`); return ''; }
  if (head.startsWith('CREATE TABLE') || head.startsWith('CREATE TEMP')) return translateCreateTable(s, ctx);
  if (/^CREATE (UNIQUE )?INDEX/.test(head)) return translateCreateIndex(s, ctx);
  if (head.startsWith('CREATE TRIGGER')) return translateTrigger(s, ctx);
  if (head.startsWith('CREATE VIEW')) return `${translateExpr(s).trim()};`;
  if (head.startsWith('CREATE VIRTUAL')) throw new UnsupportedSqlError('CREATE VIRTUAL TABLE (FTS) needs a hand-written override');
  if (head.startsWith('ALTER TABLE')) return translateAlterTable(s, ctx);
  if (head.startsWith('DROP ')) return translateDrop(s, ctx);
  if (head.startsWith('INSERT')) return translateInsert(s, ctx);
  if (head.startsWith('UPDATE') || head.startsWith('DELETE') || head.startsWith('SELECT') || head.startsWith('WITH')) return `${translateExpr(s).trim()};`;
  if (head.startsWith('REPLACE')) throw new UnsupportedSqlError('REPLACE INTO needs a hand-written ON CONFLICT');
  throw new UnsupportedSqlError(`statement not supported: ${s.slice(0, 80)}`);
}

/** Columns whose line comment mentions JSON: "table.col" (lower case). */
function collectJsonHints(sql) {
  const hints = new Set();
  let table = null;
  for (const line of sql.split('\n')) {
    const t = /CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?(\w+)/i.exec(line);
    if (t) table = t[1];
    const alter = /ALTER\s+TABLE\s+(\w+)\s+ADD\s+(?:COLUMN\s+)?(\w+)/i.exec(line);
    const idx = line.indexOf('--');
    if (idx < 0 || !/json/i.test(line.slice(idx))) continue;
    if (alter) { hints.add(`${alter[1]}.${alter[2]}`.toLowerCase()); continue; }
    const col = /^\s*(\w+)\s+\w+/.exec(line.slice(0, idx));
    if (col && table) hints.add(`${table}.${col[1]}`.toLowerCase());
  }
  return hints;
}

/**
 * Translate a whole SQLite script with the shared state.
 * Returns { sql, notes, jsonCandidates }.
 */
export function translateSql(sql, state = createState()) {
  const ctx = { state, notes: [], jsonCandidates: [], jsonHints: collectJsonHints(sql) };
  const out = [];
  for (const stmt of splitStatements(stripComments(sql))) {
    const t = translateStatement(stmt, ctx);
    if (t) out.push(t);
  }
  return { sql: out.join('\n\n') + (out.length ? '\n' : ''), notes: ctx.notes, jsonCandidates: ctx.jsonCandidates };
}

