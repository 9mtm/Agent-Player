export function listSources(dbDir) {
  const migDir = join(dbDir, 'migrations');
  const files = readdirSync(migDir).filter((f) => f.endsWith('.sql')).sort(); // same order as the runner
  return [
    { name: '000_schema', sql: readFileSync(join(dbDir, 'schema.sql'), 'utf8') + '\n' + RUNNER_MIGRATIONS_TABLE + '\n', source: 'src/db/schema.sql + runner migrations table' },
    ...files.map((f) => ({ name: f.replace(/\.sql$/, ''), sql: readFileSync(join(migDir, f), 'utf8'), source: `src/db/migrations/${f}` })),
  ];
}

export function translateAll(backendDir) {
  const dbDir = join(backendDir, 'src', 'db');
  const overridesDir = join(backendDir, 'scripts', 'pg', 'overrides');
  const st = createState();
  const results = [];
  for (const src of listSources(dbDir)) {
    const overridePath = join(overridesDir, `${src.name}.sql`);
    let res;
    let error = null;
    try {
      res = translateSql(src.sql, st);
    } catch (e) {
      if (!(e instanceof UnsupportedSqlError)) throw e;
      error = e.message;
      res = { sql: '', notes: [], jsonCandidates: [] };
    }
    const override = existsSync(overridePath) ? readFileSync(overridePath, 'utf8') : null;
    if (error && !override) throw new UnsupportedSqlError(`${src.source}: ${error} (add scripts/pg/overrides/${src.name}.sql)`);
    const header = [
      `-- PostgreSQL translation of ${src.source}`,
      override
        ? `-- HAND-WRITTEN override: scripts/pg/overrides/${src.name}.sql${error ? ` (automatic translation failed: ${error})` : ''}`
        : '-- Generated by scripts/pg/translate-migrations.mjs. Do not edit; change the translator or add an override.',
      ...res.notes.map((n) => `-- note: ${n}`),
      ...(res.jsonCandidates.length ? [`-- jsonb candidates (kept as text): ${res.jsonCandidates.join(', ')}`] : []),
    ].join('\n');
    results.push({ name: src.name, file: `${src.name}.sql`, override: !!override, notes: res.notes, jsonCandidates: res.jsonCandidates, content: `${header}\n\n${override ?? res.sql}` });
  }
  return results;
}

function main() {
  const here = dirname(fileURLToPath(import.meta.url));
  const backendDir = resolve(here, '..', '..');
  const outDir = join(backendDir, 'src', 'db', 'migrations-pg');
  const check = process.argv.includes('--check');
  const results = translateAll(backendDir);
  let diff = 0;
  if (!check) mkdirSync(outDir, { recursive: true });
  for (const r of results) {
    const p = join(outDir, r.file);
    if (check) {
      if (!existsSync(p) || readFileSync(p, 'utf8') !== r.content) { console.error(`differs: ${r.file}`); diff++; }
    } else {
      writeFileSync(p, r.content);
    }
  }
  const stale = existsSync(outDir) ? readdirSync(outDir).filter((f) => f.endsWith('.sql') && !results.some((r) => r.file === f)) : [];
  for (const f of stale) { console.error(`stale output (no source): ${f}`); diff++; }
  const overrides = results.filter((r) => r.override).map((r) => r.file);
  const notes = results.reduce((n, r) => n + r.notes.length, 0);
  const json = results.flatMap((r) => r.jsonCandidates);
  console.log(`${check ? 'checked' : 'wrote'} ${results.length} files in ${outDir}`);
  console.log(`overrides: ${overrides.length ? overrides.join(', ') : 'none'}; notes: ${notes}; jsonb candidates: ${json.length}`);
  if (diff) { console.error(`${diff} file(s) out of date; run without --check`); process.exit(1); }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) main();
