#!/usr/bin/env node
/**
 * B2.1: translate the SQLite schema and migrations into PostgreSQL DDL.
 *
 * Input, in the same order the SQLite runner (src/db/database.ts) applies it:
 *   1. src/db/schema.sql (+ the runner's own `migrations` table)
 *   2. src/db/migrations/*.sql, sorted by file name (`.sql.disabled` skipped)
 * Output: src/db/migrations-pg/<same base name>.sql (000_schema.sql for 1.)
 *
 * Plain Node, no dependencies. A file in scripts/pg/overrides/<name>.sql
 * replaces the generated output for that migration (hand-written override).
 *
 * Usage: node scripts/pg/translate-migrations.mjs [--check]
 *   --check  translate in memory and fail if the committed output differs.
 *
 * Mapping (see the header of each generated file for per-file notes):
 *   INTEGER [PRIMARY KEY [AUTOINCREMENT]] -> bigint [GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY]
 *   BOOLEAN -> integer (0/1 kept; TRUE/FALSE defaults -> 1/0)
 *   REAL -> double precision, BLOB -> bytea, JSON -> text (jsonb candidate)
 *   DATETIME / TIMESTAMP -> timestamptz; CURRENT_TIMESTAMP / datetime('now') -> now()
 *   TEXT columns keep their string format: datetime('now') / CURRENT_TIMESTAMP ->
 *     to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'); strftime(fmt,'now') -> to_char
 *   lower(hex(randomblob(N))) -> hex from gen_random_uuid() (built in, no pgcrypto)
 *   INSERT OR IGNORE -> INSERT ... ON CONFLICT DO NOTHING
 *   CREATE TRIGGER -> plpgsql function + trigger (self-row UPDATE -> BEFORE trigger)
 *   COLLATE NOCASE -> dropped (noted), PRAGMA -> dropped
 *   FOREIGN KEY to a missing table or with a mismatched column type -> dropped (noted;
 *     SQLite accepts these, PostgreSQL refuses them)
 */

import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export class UnsupportedSqlError extends Error {}

/** DDL the SQLite runner executes itself before the migrations. */
export const RUNNER_MIGRATIONS_TABLE = `CREATE TABLE IF NOT EXISTS migrations (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  applied_at DATETIME DEFAULT CURRENT_TIMESTAMP
);`;

const PG_RESERVED = new Set(('all analyse analyze and any array as asc asymmetric both case cast check collate column ' +
  'constraint create current_catalog current_date current_role current_time current_timestamp current_user default ' +
  'deferrable desc distinct do else end except false fetch for foreign from grant group having in initially intersect ' +
  'into lateral leading limit localtime localtimestamp not null offset on only or order placing primary references ' +
  'returning select session_user some symmetric system_user table then to trailing true union unique user using ' +
  'variadic when where window with authorization binary collation concurrently cross current_schema freeze full ' +
  'ilike inner is isnull join left like natural notnull outer overlaps right similar tablesample verbose').split(' '));

const COLUMN_CONSTRAINT_WORDS = new Set(['CONSTRAINT', 'PRIMARY', 'NOT', 'NULL', 'UNIQUE', 'CHECK', 'DEFAULT',
  'REFERENCES', 'COLLATE', 'GENERATED', 'AS', 'AUTOINCREMENT']);

const TEXT_NOW = `to_char((now() AT TIME ZONE 'UTC'), 'YYYY-MM-DD HH24:MI:SS')`;
const JSON_NAME_RE = /(^|_)(json|metadata|meta|settings|config|capabilities|tags|options|changes|evidence|traits|args|scopes|layout|state|schema|annotations|items|files|summary|receipt|reasons|checks|attendees|reminders|permissions|dependencies|widgets)$/i;

